#!/usr/bin/env python3
"""Build OpenCode's global rules file from the shared agent instructions.

OpenCode reads ~/.config/opencode/AGENTS.md but does not expand `@file` lines, and its
`instructions` config key loaded nothing on 2.0.10 (measured 2026-10-16). This writes
~/.config/ai/INSTRUCTIONS.md with each `@NAME.md` line replaced by that file, the same
result Claude Code gets from its imports. Run by the knowledge Stop hook every turn.
"""
import os
import re

HOME = os.path.expanduser("~")
SRC = os.path.join(HOME, ".config/ai/INSTRUCTIONS.md")
OUT = os.path.join(HOME, ".config/opencode/AGENTS.md")
HEAD = "<!-- Generated by ~/.claude/scripts/build-opencode-agents.py from ~/.config/ai/INSTRUCTIONS.md. Do not edit. -->\n\n"


def expand(line):
    m = re.fullmatch(r"@(\S+\.md)\s*", line)
    if not m:
        return line
    path = os.path.join(os.path.dirname(SRC), m.group(1))
    return open(path, encoding="utf-8").read().rstrip("\n") + "\n"


text = HEAD + "".join(expand(l) for l in open(SRC, encoding="utf-8").read().splitlines(keepends=True))
if os.path.islink(OUT):
    os.remove(OUT)
old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
if text != old:
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
